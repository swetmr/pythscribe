/// Normalized comparison key for alias detection. Canonicalizes the file when
/// it exists, else its parent (the common case for fresh outputs), so `./a.js`
/// and `a.js` and `sub/../a.js` all collide. Case-folded on Windows.
fn alias_key(p: &Path) -> String {
    let norm = match std::fs::canonicalize(p) {
        Ok(c) => c,
        Err(_) => {
            let parent = p
                .parent()
                .filter(|q| !q.as_os_str().is_empty())
                .unwrap_or(Path::new("."));
            let base = p.file_name().map(|b| b.to_os_string()).unwrap_or_default();
            match std::fs::canonicalize(parent) {
                Ok(cp) => cp.join(base),
                Err(_) => p.to_path_buf(),
            }
        }
    };
    let s = norm.to_string_lossy().into_owned();
    // Round-5: case-fold on macOS too — default APFS/HFS+ are case-
    // insensitive, so `worker.WASM` and `worker.wasm` are ONE file there and
    // must collide in the alias check. (Residual, documented: a
    // case-insensitive mount on Linux, or a case-SENSITIVE volume on macOS,
    // is not detected — the per-destination exclusive-create/fd checks still
    // fail closed on the actual collision, just later and less tidily.)
    if cfg!(any(windows, target_os = "macos")) {
        s.to_lowercase()
    } else {
        s
    }
}

/// State of an output path after a no-follow inspection.
enum Inspection {
    Absent,
    Existing(std::fs::Metadata),
}

/// SEC #5/#10/#12: shared no-follow, fail-closed inspection for EVERY
/// destination. `symlink_metadata` sees the link itself (unlike
/// `Path::exists`, which follows and reports a DANGLING link as absent — the
/// #12 scaffold bug), so symlinks are refused here rather than followed.
/// Non-regular files are refused, and any metadata error other than "not
/// found" fails closed: if we cannot prove the destination is safe we do not
/// write it.
fn inspect(target: &Path) -> Result<Inspection, BoxError> {
    match std::fs::symlink_metadata(target) {
        Ok(meta) => {
            let ft = meta.file_type();
            if ft.is_symlink() {
                return Err(format!(
                    "refusing to write generated output through a symlink:\n    {}\n  \
                     this path is a symbolic link; writing would modify its target instead of \
                     creating a compiled output.\n  \
                     Remove the link or choose a different output path (-o).",
                    target.display()
                )
                .into());
            }
            if !ft.is_file() {
                return Err(format!(
                    "refusing to write generated output over a non-regular file \
                     (directory, device, or pipe):\n    {}",
                    target.display()
                )
                .into());
            }
            Ok(Inspection::Existing(meta))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Inspection::Absent),
        Err(e) => Err(format!(
            "refusing to write generated output: could not inspect the destination\n    {}\n  \
             {} — cannot prove it is safe to write.",
            target.display(),
            e
        )
        .into()),
    }
}

fn hardlink_refusal(target: &Path, nlink: u64) -> BoxError {
    format!(
        "refusing to write generated output to a file with a hard-link count of {}:\n    {}\n  \
         a link count above 1 means writing would rewrite the file's other names too; \
         0 means it was unlinked while being inspected.\n  \
         Break the link (or re-run the build) or choose a different output path (-o).",
        nlink,
        target.display()
    )
    .into()
}

/// Preflight one destination against the full plan.
fn decide(o: &PlannedOutput, all: &[PlannedOutput], force: bool) -> Result<Decision, BoxError> {
    match inspect(&o.path)? {
        Inspection::Absent => return Ok(Decision::Create),
        Inspection::Existing(_) => {}
    }

    // Existing scaffold: kept untouched, so no further checks apply.
    if matches!(o.kind, OutputKind::ScaffoldIfAbsent) {
        return Ok(Decision::Keep);
    }

    // Round-6: ALL preflight facts about the existing destination — link
    // count (item 6/7: same rejection the writer applies, so refusals
    // surface before anything else in the graph is written; round-5:
    // Windows too), FILE IDENTITY, and the ownership/content evidence —
    // come from ONE open handle, so they provably describe the same file.
    // The identity travels in the proof and is re-verified on the WRITING
    // fd, which closes the substitution race the evidence alone left open
    // (a different PythScribe-marked file renamed over the destination
    // after preflight).
    let f = open_no_follow_read(&o.path)?;
    let fmeta = f.metadata()?;
    if !fmeta.file_type().is_file() {
        return Err(format!(
            "refusing to write generated output over a non-regular file:\n    {}",
            o.path.display()
        )
        .into());
    }
    {
        let n = link_count_on_fd(&f, &fmeta)?;
        if n != 1 {
            return Err(hardlink_refusal(&o.path, n));
        }
    }
    let identity = file_identity(&f)?;

    if force {
        // --force authorizes destroying THIS file — record its identity and
        // exact bytes so the writer can prove, on the fd, that it is still
        // the very same file.
        let bytes = read_all_on(&f, &o.path)?;
        return Ok(Decision::Overwrite(OverwriteProof {
            identity,
            evidence: Evidence::Bytes(bytes),
        }));
    }

    match &o.kind {
        OutputKind::MarkedText => {
            let mut head = Vec::new();
            if Read::take(&f, 4096).read_to_end(&mut head).is_ok() && looks_pyths_generated(&head)
            {
                Ok(Decision::Overwrite(OverwriteProof {
                    identity,
                    evidence: Evidence::MarkerOnFd,
                }))
            } else {
                Err(format!(
                    "refusing to overwrite a file PythScribe did not generate:\n    {}\n  \
                     it lacks the `{}` marker, so it looks hand-written and would be lost.\n  \
                     Move it aside, choose a different output path (-o), or pass --force.",
                    o.path.display(),
                    GENERATED_MARKER
                )
                .into())
            }
        }
        OutputKind::WasmModule => {
            let bytes = read_all_on(&f, &o.path)?;
            if pyths_codegen_wasm::optimize::has_generated_marker(&bytes) {
                Ok(Decision::Overwrite(OverwriteProof {
                    identity,
                    evidence: Evidence::WasmSectionOnFd,
                }))
            } else {
                Err(format!(
                    "refusing to overwrite a `.wasm` PythScribe cannot prove it created:\n    {}\n  \
                     it lacks the `{}` ownership section. Modules built by PythScribe ≥ 0.2.2 \
                     carry it; pass --force once to adopt an older or foreign file, or build \
                     into a clean output directory.",
                    o.path.display(),
                    pyths_codegen_wasm::optimize::GENERATED_SECTION_NAME
                )
                .into())
            }
        }
        OutputKind::Sidecar { primary } => {
            if primary_is_owned(primary, all)? {
                // The sidecar itself is marker-less, so the writer cannot
                // prove OWNERSHIP on the fd — instead it proves identity:
                // the file's on-disk identity plus the exact bytes whose
                // destruction the owned primary authorizes; anything else on
                // the fd at write time is refused (round-5 fix: no
                // proof-free overwrite path).
                let bytes = read_all_on(&f, &o.path)?;
                Ok(Decision::Overwrite(OverwriteProof {
                    identity,
                    evidence: Evidence::Bytes(bytes),
                }))
            } else {
                Err(format!(
                    "refusing to overwrite an existing file with a generated sidecar \
                     output:\n    {}\n  \
                     it carries no ownership marker, and its primary output\n    {}\n  \
                     is not a PythScribe-generated file it could belong to — so PythScribe \
                     cannot prove the sidecar is its own.\n  \
                     Move it aside, pass --force, or build into a clean output directory.",
                    o.path.display(),
                    primary.display()
                )
                .into())
            }
        }
        OutputKind::ScaffoldIfAbsent => unreachable!("handled above"),
    }
}

/// Is the sidecar's primary output an EXISTING file that PythScribe owns?
/// A fresh (absent) primary returns `false` — absence authorizes nothing
/// (round-3 blocking finding: `app.js` absent + handwritten `app.js.map`
/// must NOT let `--sourcemap` destroy the map).
fn primary_is_owned(primary: &Path, all: &[PlannedOutput]) -> Result<bool, BoxError> {
    let meta = match std::fs::symlink_metadata(primary) {
        Ok(m) => m,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(e) => {
            return Err(format!(
                "refusing to write generated output: could not inspect the primary output\n    \
                 {}\n  {} — cannot prove its sidecar is safe to write.",
                primary.display(),
                e
            )
            .into())
        }
    };
    if !meta.file_type().is_file() {
        return Ok(false);
    }
    // The primary's kind decides which ownership proof applies.
    let is_wasm_primary = all
        .iter()
        .find(|p| p.path == primary)
        .map(|p| matches!(p.kind, OutputKind::WasmModule))
        .unwrap_or_else(|| {
            primary
                .extension()
                .map(|e| e.eq_ignore_ascii_case("wasm"))
                .unwrap_or(false)
        });
    if is_wasm_primary {
        Ok(std::fs::read(primary)
            .map(|b| pyths_codegen_wasm::optimize::has_generated_marker(&b))
            .unwrap_or(false))
    } else {
        Ok(read_head(primary, 4096)
            .map(|h| looks_pyths_generated(&h))
            .unwrap_or(false))
    }
}

fn read_head(path: &Path, limit: u64) -> std::io::Result<Vec<u8>> {
    let f = std::fs::File::open(path)?;
    let mut head = Vec::new();
    f.take(limit).read_to_end(&mut head)?;
    Ok(head)
}

