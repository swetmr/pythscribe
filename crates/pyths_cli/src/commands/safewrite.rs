//! safewrite.rs — THE one canonical safe-write API for every generated output.
//!
//! Rounds 1–3 of the 2026-08 security campaign patched generated-output
//! writing per call site (js, dts, map, wasm, glue, cert, edge entry,
//! scaffolds), and each site re-derived its own inspection, ownership, and
//! ordering logic — which is exactly how the residual TOCTOU / platform
//! defects survived three review rounds. Round 4 closes the CLASS instead:
//! this module is the single place that knows how to write a generated
//! output, and `compile.rs` / `bundle.rs` only *declare* what they intend to
//! write.
//!
//! ## The model
//!
//! 1. **Declare the complete output graph.** A command builds a
//!    `Vec<PlannedOutput>` — every destination it could touch — and calls
//!    [`OutputPlan::preflight`] ONCE before any write (P10). Preflight applies
//!    the SAME checks the final writer applies (symlink, non-regular file,
//!    hard-link count, ownership) plus destination-ALIAS detection (two
//!    planned outputs resolving to one file, e.g. `--target deno -o
//!    worker.wasm`), so no refusal the preflight can detect surfaces after a
//!    partial write. Honest scope: this REDUCES partial-artifact risk, it
//!    does not eliminate it — writes are sequential, so a mid-sequence
//!    failure (ENOSPC, or a destination appearing between preflight and its
//!    exclusive create) still leaves the outputs written before it; a
//!    partial artifact is later rebuilt (marker intact) or refused with an
//!    explicit error, never silently trusted.
//!
//! 2. **Ownership is proven on the artifact itself, on the writing fd.**
//!    * Text outputs carry the leading `// @generated by PythScribe` marker.
//!    * `.wasm` outputs carry a `pythscribe.generated` WASM custom section
//!      (see `pyths_codegen_wasm::optimize`) — so the tool's OWN rebuild
//!      succeeds without `--force`, while a truly-unowned `.wasm` is refused.
//!    * Marker-less sidecars (`.map`, `.cert.json`) are overwritable only if
//!      the SIDECAR ITSELF is absent, or its primary EXISTS AND IS OWNED —
//!      a fresh (absent) primary never authorizes destroying an unowned
//!      sidecar. Because a sidecar cannot prove ownership on the fd, the
//!      writer proves content identity instead: the fd's content must be
//!      byte-identical to what preflight authorized (same for `--force`).
//!      There is no proof-free overwrite path.
//!    * Round-6: on top of the evidence, EVERY overwrite is bound to the
//!      FILE IDENTITY (dev+inode / volume+file-index) captured at preflight
//!      from the same handle that read the evidence, and re-verified on the
//!      writing fd. Evidence alone is forgeable by construction (see the
//!      trust-model section below); the identity is what refuses a
//!      DIFFERENT, genuinely-marked file renamed over the destination after
//!      preflight. `rewrite` (wasm-opt placement) is likewise bound to the
//!      identity of the file this same invocation wrote.
//!
//! 3. **One fd-verified writer.** Overwrites open WITHOUT truncate
//!    (`libc::O_NOFOLLOW` on unix — the per-arch-correct constant; a
//!    hardcoded value was wrong on aarch64-linux, a released target), fstat
//!    the fd (regular file, link count EXACTLY 1 — 0 means the destination
//!    was unlinked after our open and this is an orphan; enforced on unix
//!    via fstat and on Windows via `GetFileInformationByHandle` on the same
//!    handle), verify the ownership/identity proof ON THAT SAME fd, and only
//!    then `set_len(0)` + `write_all` on the same handle. Fresh creations
//!    are `O_EXCL`.
//!
//! ## What the ownership marker is — and is NOT
//!
//! The marker (text header / wasm custom section) is **accident
//! prevention**: it stops the compiler from clobbering a file a HUMAN put
//! there — a hand-written `Counter.js`, a foreign `.wasm`, a stale artifact
//! from another tool. It is **not a security boundary against a malicious
//! local process**: anyone who can write to the build directory can also
//! paste the `@generated` line or append the custom section and "forge"
//! ownership — and equally could have written the destination directly.
//! Defending files from an attacker who already has write access to the same
//! directory is out of scope for any marker scheme; that case belongs to
//! filesystem permissions and the OS trust boundary (see docs/security.md
//! §1/§6). The fd-verified writer's job is narrower and real: no-follow
//! opens on POSIX (`O_NOFOLLOW`; Windows has no such flag — the pre-open
//! `symlink_metadata` check plus privilege-gated symlink creation is the
//! documented residual there, e.g. a link to a saved copy of the SAME file
//! swapped in after preflight passes identity+evidence and the write
//! follows it), never truncate before the identity+ownership proof, never
//! write what preflight did not authorize.
//!
//! ## Documented residuals (platform)
//!
//! * **Windows** has no `O_NOFOLLOW`; the overwrite path relies on the
//!   pre-open `symlink_metadata` plus the fd proof. Symlink creation there
//!   is privilege-gated (admin / developer mode), so the exposure is
//!   accepted and documented rather than claimed closed.
//! * **Case-folding** in alias detection covers Windows and macOS defaults;
//!   a case-insensitive mount on Linux (or a case-sensitive APFS volume) is
//!   not modeled — the exclusive-create/fd checks still fail closed on the
//!   real collision, only later.

use std::collections::HashMap;
use std::io::{Read, Seek, SeekFrom, Write};
use std::path::{Path, PathBuf};

type BoxError = Box<dyn std::error::Error>;

/// Marker embedded at the top of every generated text output. A later
/// compile recognizes its own output by this marker and safely overwrites it,
/// while a hand-written file that lacks the marker is protected (A8).
pub const GENERATED_MARKER: &str = "@generated by PythScribe";

/// The header line prepended to generated `.js` / `.d.ts` / glue output.
pub(crate) fn generated_header() -> String {
    format!(
        "// {} — do not edit; regenerate with `pyths compile`.\n",
        GENERATED_MARKER
    )
}

/// Does this file content look like PythScribe-generated output? P4: the marker
/// must be the LEADING `//` comment, not a substring anywhere in the first 512
/// bytes — a hand-written file that merely mentions "@generated by PythScribe"
/// (e.g. in a doc comment) must NOT be treated as owned and overwritten.
pub(crate) fn looks_pyths_generated(bytes: &[u8]) -> bool {
    let head_len = bytes.len().min(512);
    let head = String::from_utf8_lossy(&bytes[..head_len]);
    head.trim_start()
        .starts_with(&format!("// {}", GENERATED_MARKER))
}

/// What kind of generated output a destination is — this decides how its
/// ownership is proven.
#[derive(Clone, Debug)]
pub enum OutputKind {
    /// `.js` / `.d.ts` / `.glue.js` / edge entry / bundle — owned via the
    /// leading `// @generated` marker, verified on the writing fd.
    MarkedText,
    /// `.wasm` — owned via the `pythscribe.generated` custom section,
    /// verified on the writing fd.
    WasmModule,
    /// Marker-less sidecar (`.js.map`, `.cert.json`, `.wasm.cert.json`) —
    /// overwritable only when absent or when `primary` exists AND is owned.
    /// A fresh (absent) primary authorizes NOTHING.
    Sidecar { primary: PathBuf },
    /// Fixed-name scaffold config (`wrangler.toml`, `package.json`,
    /// `deno.json`): an existing regular file is KEPT (the user's config
    /// wins); symlinks — including dangling ones — are refused; creation is
    /// exclusive.
    ScaffoldIfAbsent,
}

/// One destination the current command intends to write.
pub struct PlannedOutput {
    pub path: PathBuf,
    pub kind: OutputKind,
}

impl PlannedOutput {
    pub fn marked_text(path: impl Into<PathBuf>) -> Self {
        PlannedOutput { path: path.into(), kind: OutputKind::MarkedText }
    }
    pub fn wasm(path: impl Into<PathBuf>) -> Self {
        PlannedOutput { path: path.into(), kind: OutputKind::WasmModule }
    }
    pub fn sidecar(path: impl Into<PathBuf>, primary: impl Into<PathBuf>) -> Self {
        PlannedOutput {
            path: path.into(),
            kind: OutputKind::Sidecar { primary: primary.into() },
        }
    }
    pub fn scaffold(path: impl Into<PathBuf>) -> Self {
        PlannedOutput { path: path.into(), kind: OutputKind::ScaffoldIfAbsent }
    }
}

/// Preflight decision for one destination.
#[derive(Debug)]
enum Decision {
    /// Nothing was there — create exclusively (`O_EXCL`).
    Create,
    /// An authorized file was there — fd-verified overwrite carrying the
    /// EXACT proof the writer must re-establish on the fd. There is no
    /// proof-free overwrite path (round-5 fix): even `--force` and sidecar
    /// overwrites verify, on the writing fd, that the file being truncated is
    /// byte-identical to the one preflight authorized destroying — and every
    /// proof also carries the FILE IDENTITY preflight captured, so only that
    /// very file, not a marked or byte-identical substitute, can be
    /// overwritten (round-6 fix).
    Overwrite(OverwriteProof),
    /// Existing scaffold — keep the user's file, write nothing.
    Keep,
}

/// How ownership/identity is proven ON THE WRITING FD before any truncation.
///
/// Round-6: EVERY overwrite proof carries the [`FileIdentity`] captured at
/// preflight, and the writer verifies it on the writing fd BEFORE the
/// evidence check. The evidence alone was not enough: a DIFFERENT
/// PythScribe-marked file renamed over the destination after preflight
/// carried a valid marker and was truncated. Binding the write to the exact
/// (volume, file-id) pair preflight inspected closes that substitution class
/// — only the SAME file preflight authorized destroying can be overwritten,
/// never merely "some marked file".
#[derive(Debug)]
struct OverwriteProof {
    /// The exact file preflight authorized overwriting.
    identity: FileIdentity,
    /// The ownership/content evidence re-established on the writing fd.
    evidence: Evidence,
}

#[derive(Debug)]
enum Evidence {
    /// Leading `// @generated` marker read from the fd.
    MarkerOnFd,
    /// `pythscribe.generated` WASM custom section read from the fd.
    WasmSectionOnFd,
    /// The exact bytes preflight authorized destroying (`--force`, or a
    /// marker-less sidecar whose primary is owned). The fd's current content
    /// must equal them — a same-file content change after preflight is
    /// refused (a different-file swap is already refused by the identity).
    Bytes(Vec<u8>),
}

/// A file's stable on-disk identity: `(device, inode)` on unix,
/// `(volume serial, file index)` on Windows (`GetFileInformationByHandle`
/// through the safe `winapi-util` wrapper — keeps the compiler
/// `unsafe`-free). Hard links share an identity; the exactly-1 link-count
/// check is what rules those out. What THIS rules out is substitution: a
/// different file moved over the destination after preflight has a different
/// identity, marker or no marker. (Residual, documented: a filesystem that
/// does not report stable 64-bit file IDs weakens this to the evidence
/// checks; NTFS/ext4/APFS — everything we ship to — reports them.)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct FileIdentity {
    volume: u64,
    file: u64,
}

/// Identity of an OPEN file, read from the handle itself (never a fresh
/// path lookup — the whole point is that the handle is the thing we verified
/// and will truncate). Fails CLOSED: if the identity cannot be queried, the
/// write is refused.
fn file_identity(f: &std::fs::File) -> Result<FileIdentity, BoxError> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        let m = f.metadata()?;
        Ok(FileIdentity { volume: m.dev(), file: m.ino() })
    }
    #[cfg(windows)]
    {
        let info = winapi_util::file::information(f).map_err(|e| -> BoxError {
            format!(
                "refusing to write generated output: could not query the destination's \
                 file identity ({}) — cannot prove it is the file the pre-flight check \
                 authorized overwriting.",
                e
            )
            .into()
        })?;
        Ok(FileIdentity {
            volume: info.volume_serial_number(),
            file: info.file_index(),
        })
    }
    #[cfg(not(any(unix, windows)))]
    {
        let _ = f;
        // No identity primitive on this platform (none we ship to) — the
        // evidence checks still apply. Documented residual.
        Ok(FileIdentity { volume: 0, file: 0 })
    }
}

/// The preflighted output plan. Every write MUST go through [`OutputPlan::write`];
/// a path that was not preflighted is refused (fail closed) — that is the
/// mechanism that keeps future call sites from bypassing the checks.
#[derive(Debug)]
pub struct OutputPlan {
    entries: HashMap<PathBuf, (Decision, OutputKind)>,
    /// Identity of each file THIS plan wrote in THIS invocation, captured
    /// from the writing handle itself. `rewrite` verifies against it, so a
    /// re-write can only ever land on the exact file this invocation
    /// produced (round-6 fix — a marker-bearing file swapped in between
    /// `write` and `rewrite` no longer passes on its marker alone).
    written: std::sync::Mutex<HashMap<PathBuf, FileIdentity>>,
}

impl OutputPlan {
    /// Check EVERY declared destination — existence, symlink, dir-vs-file,
    /// hard-link count, ownership, and destination aliasing — BEFORE any
    /// write. Returns the plan on success; any refusal aborts the whole
    /// command with nothing written.
    pub fn preflight(outputs: &[PlannedOutput], force: bool) -> Result<OutputPlan, BoxError> {
        // Destination aliasing: two planned outputs must never resolve to the
        // same file (e.g. `--target deno -o worker.wasm` makes the WASM and
        // the entry identical; `-o app.out` makes the `.d.ts` path collide
        // with the `.js`). Both would pass individual checks as "absent" and
        // then clobber each other.
        let mut seen: HashMap<String, &Path> = HashMap::new();
        for o in outputs {
            if let Some(prev) = seen.insert(alias_key(&o.path), &o.path) {
                return Err(format!(
                    "refusing to build: two generated outputs resolve to the same \
                     destination:\n    {}\n    {}\n  \
                     Choose a different output path (-o) so every artifact has its own file.",
                    prev.display(),
                    o.path.display()
                )
                .into());
            }
        }

        let mut entries = HashMap::new();
        for o in outputs {
            let decision = decide(o, outputs, force)?;
            entries.insert(o.path.clone(), (decision, o.kind.clone()));
        }
        Ok(OutputPlan {
            entries,
            written: std::sync::Mutex::new(HashMap::new()),
        })
    }

    /// Write one preflighted destination. Returns `Ok(true)` if bytes were
    /// written, `Ok(false)` if an existing scaffold was kept.
    pub fn write(&self, path: &Path, contents: &[u8]) -> Result<bool, BoxError> {
        let (decision, kind) = self.entries.get(path).ok_or_else(|| -> BoxError {
            format!(
                "internal error: write of an unplanned output:\n    {}\n  \
                 every generated output must be declared to OutputPlan::preflight first.",
                path.display()
            )
            .into()
        })?;
        let _ = kind;
        match decision {
            Decision::Keep => Ok(false),
            Decision::Create => {
                let id = create_new_write(path, contents)?;
                self.written.lock().unwrap().insert(path.to_path_buf(), id);
                Ok(true)
            }
            Decision::Overwrite(proof) => {
                let id = overwrite_on_fd(path, contents, proof)?;
                self.written.lock().unwrap().insert(path.to_path_buf(), id);
                Ok(true)
            }
        }
    }

    /// Re-write a destination this plan already wrote in THIS invocation
    /// (wasm-opt's optimized module replacing the fresh `.wasm` we produced
    /// moments earlier). The destination must be planned AND already written
    /// by this plan; the write is fd-verified against BOTH the identity of
    /// the file our own `write` produced (captured from the writing handle —
    /// round-6 fix: a DIFFERENT marker-bearing file swapped in since our
    /// write has a different identity and is refused) and the artifact's own
    /// ownership evidence (round-5 fix: the optimized module used to be
    /// `fs::rename`d over the destination unverified).
    pub fn rewrite(&self, path: &Path, contents: &[u8]) -> Result<(), BoxError> {
        let (_, kind) = self.entries.get(path).ok_or_else(|| -> BoxError {
            format!(
                "internal error: rewrite of an unplanned output:\n    {}\n  \
                 every generated output must be declared to OutputPlan::preflight first.",
                path.display()
            )
            .into()
        })?;
        let identity = self
            .written
            .lock()
            .unwrap()
            .get(path)
            .copied()
            .ok_or_else(|| -> BoxError {
                format!(
                    "internal error: rewrite of an output this invocation has not \
                     written:\n    {}\n  \
                     rewrite may only replace an artifact this same plan produced.",
                    path.display()
                )
                .into()
            })?;
        let evidence = match kind {
            OutputKind::MarkedText => Evidence::MarkerOnFd,
            OutputKind::WasmModule => Evidence::WasmSectionOnFd,
            _ => {
                return Err(format!(
                    "internal error: rewrite is only supported for outputs that carry their \
                     own ownership proof (text marker / wasm section):\n    {}",
                    path.display()
                )
                .into())
            }
        };
        let proof = OverwriteProof { identity, evidence };
        let id = overwrite_on_fd(path, contents, &proof)?;
        self.written.lock().unwrap().insert(path.to_path_buf(), id);
        Ok(())
    }
}

/// Single-destination convenience (bundle output, cache-hit copy): preflight
/// one output and write it.
pub fn write_single(
    path: &Path,
    contents: &[u8],
    kind: OutputKind,
    force: bool,
) -> Result<bool, BoxError> {
    let planned = [PlannedOutput { path: path.to_path_buf(), kind }];
    let plan = OutputPlan::preflight(&planned, force)?;
    plan.write(path, contents)
}

