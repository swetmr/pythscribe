/// Create a brand-new file EXCLUSIVELY (`O_EXCL`/`CREATE_NEW`). If anything —
/// a real file, or a symlink that raced the preflight — appears at the path,
/// the create fails with `AlreadyExists` and is refused rather than followed.
/// This closes the inspect→write TOCTOU window for every fresh creation.
fn create_new_write(target: &Path, contents: &[u8]) -> Result<FileIdentity, BoxError> {
    match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(target)
    {
        Ok(mut f) => {
            f.write_all(contents)?;
            // Identity of the file WE created, from our own handle — this is
            // what a later `rewrite` of the same destination must match.
            file_identity(&f)
        }
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => Err(format!(
            "refusing to write generated output: the destination appeared while it was being \
             checked:\n    {}\n  Re-run the build.",
            target.display()
        )
        .into()),
        Err(e) => Err(e.into()),
    }
}

/// Hard-link count of an opened file, per platform (round-5: Windows too).
///
///   * unix — from the fstat the writer already performed.
///   * windows — `GetFileInformationByHandle` on the SAME handle, through the
///     safe `winapi-util` wrapper (keeps the compiler `unsafe`-free). A query
///     failure fails CLOSED: if the link count cannot be proven, do not write.
///   * anywhere else — no primitive; treated as 1 (documented residual).
fn link_count_on_fd(f: &std::fs::File, meta: &std::fs::Metadata) -> Result<u64, BoxError> {
    #[cfg(unix)]
    {
        let _ = f;
        use std::os::unix::fs::MetadataExt;
        Ok(meta.nlink())
    }
    #[cfg(windows)]
    {
        let _ = meta;
        let info = winapi_util::file::information(f).map_err(|e| -> BoxError {
            format!(
                "refusing to write generated output: could not query the destination's \
                 hard-link count ({}) — cannot prove it is safe to write.",
                e
            )
            .into()
        })?;
        Ok(info.number_of_links())
    }
    #[cfg(not(any(unix, windows)))]
    {
        let _ = (f, meta);
        Ok(1)
    }
}

/// Open an existing destination READ-ONLY for preflight, no-follow on unix
/// (`libc::O_NOFOLLOW`, per-arch). The preflight facts — link count,
/// identity, evidence — are all read from this one handle so they describe
/// the same file. A failure fails closed.
fn open_no_follow_read(path: &Path) -> Result<std::fs::File, BoxError> {
    let mut opts = std::fs::OpenOptions::new();
    opts.read(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        opts.custom_flags(libc::O_NOFOLLOW);
    }
    opts.open(path).map_err(|e| -> BoxError {
        format!(
            "refusing to write generated output: could not open the destination for \
             pre-flight verification (possible symlink swapped in after inspection):\n    \
             {}\n  {}",
            path.display(),
            e
        )
        .into()
    })
}

/// Read an open handle to the end (used at preflight; the handle is fresh,
/// so this reads from offset 0).
fn read_all_on(mut f: &std::fs::File, path: &Path) -> Result<Vec<u8>, BoxError> {
    let mut bytes = Vec::new();
    f.read_to_end(&mut bytes).map_err(|e| -> BoxError {
        format!(
            "refusing to write generated output: could not read the existing \
             destination for verification:\n    {}\n  {}",
            path.display(),
            e
        )
        .into()
    })?;
    Ok(bytes)
}

/// P5 (round-4 consolidation): overwrite an EXISTING file with the ownership
/// check AND the write on ONE file handle. Correct order (never truncate
/// before verifying): open WITHOUT truncate (`libc::O_NOFOLLOW` on unix — the
/// per-arch-correct constant) → fstat the fd (regular file, `nlink == 1`
/// EXACTLY) → read the fd and verify the proof → and ONLY THEN `set_len(0)`
/// + write on that same handle.
///
/// Doing the proof on the fd (not a fresh path stat) closes BOTH the
/// symlink-swap and the plain-file-swap races: a `victim` moved over `target`
/// after preflight has our handle but not our marker, so it is refused before
/// any truncation. On Windows `O_NOFOLLOW` is unavailable and symlink creation
/// is privilege-gated — a documented residual for the `--force`/sidecar path;
/// the fd proof still catches a swapped-in file for text and wasm outputs.
fn overwrite_on_fd(
    target: &Path,
    contents: &[u8],
    proof: &OverwriteProof,
) -> Result<FileIdentity, BoxError> {
    let mut opts = std::fs::OpenOptions::new();
    opts.read(true).write(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        // ROOT FIX (round-4 blocking finding): use libc's per-architecture
        // O_NOFOLLOW. The previous hardcoded 0x20000 was the x86 value and is
        // WRONG on aarch64-linux (0x8000) — a released npm target — which made
        // the no-follow guard silently inert there.
        opts.custom_flags(libc::O_NOFOLLOW);
    }
    let mut f = opts
        .open(target)
        .map_err(|e| -> BoxError {
            format!(
                "refusing to write generated output: could not open the destination no-follow \
                 (possible symlink swapped in after inspection):\n    {}\n  {}",
                target.display(),
                e
            )
            .into()
        })?;
    let meta = f.metadata()?;
    if !meta.file_type().is_file() {
        return Err(format!(
            "refusing to write generated output over a non-regular file:\n    {}",
            target.display()
        )
        .into());
    }
    {
        // EXACTLY 1: >1 is a hard link (writing rewrites the other names);
        // 0 means the destination was unlinked after our open — this handle
        // is an orphan and "success" would write to a file that no longer
        // exists at the destination (round-3 should-fix). Round-5: enforced
        // on Windows too, on this same handle.
        let n = link_count_on_fd(&f, &meta)?;
        if n != 1 {
            return Err(hardlink_refusal(target, n));
        }
    }
    // Round-6: FILE IDENTITY first — this handle must be the very file
    // preflight authorized overwriting. Without this, a DIFFERENT
    // PythScribe-marked file renamed over the destination after preflight
    // would pass the evidence check below and be destroyed.
    let identity = file_identity(&f)?;
    if identity != proof.identity {
        return Err(format!(
            "refusing to write generated output: the destination was replaced while the \
             build was running:\n    {}\n  \
             it is no longer the same file the pre-flight check authorized overwriting \
             (a different file — even a PythScribe-generated one — was moved into place).\n  \
             Re-run the build.",
            target.display()
        )
        .into());
    }
    match &proof.evidence {
        Evidence::MarkerOnFd => {
            let mut head = Vec::new();
            Read::by_ref(&mut f).take(4096).read_to_end(&mut head)?;
            if !looks_pyths_generated(&head) {
                return Err(format!(
                    "refusing to overwrite a file PythScribe did not generate:\n    {}\n  \
                     it lacks the `{}` marker, so it looks hand-written and would be lost.\n  \
                     Move it aside, choose a different output path (-o), or pass --force.",
                    target.display(),
                    GENERATED_MARKER
                )
                .into());
            }
        }
        Evidence::WasmSectionOnFd => {
            let mut all = Vec::new();
            Read::by_ref(&mut f).read_to_end(&mut all)?;
            if !pyths_codegen_wasm::optimize::has_generated_marker(&all) {
                return Err(format!(
                    "refusing to overwrite a `.wasm` PythScribe cannot prove it created \
                     (it lacks the `{}` ownership section):\n    {}\n  Pass --force to adopt it.",
                    pyths_codegen_wasm::optimize::GENERATED_SECTION_NAME,
                    target.display()
                )
                .into());
            }
        }
        Evidence::Bytes(expected) => {
            // Round-5: no proof-free overwrite path. The fd's current content
            // must be byte-identical to what preflight authorized destroying
            // (the identity check above already refused a different-file
            // swap; this refuses a same-file content change).
            let mut all = Vec::new();
            Read::by_ref(&mut f).read_to_end(&mut all)?;
            if &all != expected {
                return Err(format!(
                    "refusing to write generated output: the destination changed while the \
                     build was running:\n    {}\n  \
                     its content no longer matches what the pre-flight check authorized \
                     overwriting.\n  Re-run the build.",
                    target.display()
                )
                .into());
            }
        }
    }
    // Identity + ownership proven on THIS handle — now it is safe to
    // truncate + write. The identity is returned so the plan can bind a
    // later `rewrite` to this exact file (truncating in place preserves it).
    f.seek(SeekFrom::Start(0))?;
    f.set_len(0)?;
    f.write_all(contents)?;
    Ok(identity)
}

// ---------------------------------------------------------------------------
// User-named outputs (`expand -o`) — no ownership marker
// ---------------------------------------------------------------------------

/// Write to a path the USER explicitly named on the command line (`pyths
/// expand -o <path>`), where the content is NOT PythScribe-marked generated
/// output: `expand` emits clean canonical `.ps`, whose only legal comment
/// syntax is Python's `#`, so the `// @generated` ownership marker cannot be
/// embedded without corrupting the source. An explicit `-o` is itself the
/// authorization to write there (like a shell `>` redirection), so no marker
/// gate applies — but this routes through the SAME no-follow / non-regular-file
/// machinery as every other generated-output writer, closing the CWE-59
/// write-*through*-a-symlink hole a bare `std::fs::write` leaves open:
///
///   * a pre-existing symlink or non-regular file (dir/device/pipe) at the
///     destination is REFUSED (via [`inspect`], which uses `symlink_metadata`
///     so a link is seen, not followed);
///   * a fresh path is created EXCLUSIVELY (`O_EXCL`/`CREATE_NEW`), so a file —
///     or a symlink — racing the check is refused, not followed;
///   * an existing plain regular file is overwritten on a no-follow fd whose
///     regular-file + `nlink == 1` invariants are re-verified on the writing
///     handle (so a symlink or hard link swapped in after `inspect` is refused
///     on unix; the Windows residual is the module-documented one — no
///     `O_NOFOLLOW`, symlink creation privilege-gated).
pub fn write_user_named(path: &Path, contents: &[u8]) -> Result<(), BoxError> {
    match inspect(path)? {
        Inspection::Absent => {
            create_new_write(path, contents)?;
            Ok(())
        }
        Inspection::Existing(_) => overwrite_plain_on_fd(path, contents),
    }
}

/// Overwrite an existing plain file the user explicitly named. No ownership
/// proof (the explicit `-o` is the authorization), but still fd-verified the
/// same way [`overwrite_on_fd`] is: open WITHOUT truncate (`libc::O_NOFOLLOW`
/// on unix — the per-arch constant), confirm the fd is a regular file with a
/// link count of EXACTLY 1, and only then `set_len(0)` + write on that same
/// handle — so a symlink or hard link swapped in after `inspect` is refused
/// rather than followed.
fn overwrite_plain_on_fd(target: &Path, contents: &[u8]) -> Result<(), BoxError> {
    let mut opts = std::fs::OpenOptions::new();
    opts.read(true).write(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        opts.custom_flags(libc::O_NOFOLLOW);
    }
    let mut f = opts.open(target).map_err(|e| -> BoxError {
        format!(
            "refusing to write output: could not open the destination no-follow \
             (possible symlink swapped in after inspection):\n    {}\n  {}",
            target.display(),
            e
        )
        .into()
    })?;
    let meta = f.metadata()?;
    if !meta.file_type().is_file() {
        return Err(format!(
            "refusing to write output over a non-regular file:\n    {}",
            target.display()
        )
        .into());
    }
    let n = link_count_on_fd(&f, &meta)?;
    if n != 1 {
        return Err(hardlink_refusal(target, n));
    }
    f.seek(SeekFrom::Start(0))?;
    f.set_len(0)?;
    f.write_all(contents)?;
    Ok(())
}

