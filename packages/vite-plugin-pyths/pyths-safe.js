// ---------------------------------------------------------------------------
// Generated-file marker (mirrors compile.rs::GENERATED_MARKER)
// ---------------------------------------------------------------------------

/** Marker the CLI stamps at the top of every generated `.js` / `.d.ts`. */
export const GENERATED_MARKER = "@generated by PythScribe";

/**
 * True iff `text` is PythScribe-generated output. P4: the marker must be the
 * LEADING `//` comment, not a substring anywhere in the first 512 bytes — a
 * hand-written file that merely mentions "@generated by PythScribe" (e.g. in
 * documentation) must NOT be treated as owned and overwritten. Mirrors
 * `compile.rs::looks_pyths_generated`.
 */
export function looksPythsGenerated(text) {
    return text.trimStart().startsWith("// " + GENERATED_MARKER);
}

// ---------------------------------------------------------------------------
// #2 — no-follow, ownership-aware sibling writer
// ---------------------------------------------------------------------------

/**
 * Write a compiler-generated sibling safely. JS port of
 * `crates/pyths_cli/src/commands/compile.rs::write_generated_sibling`.
 *
 * Refuses to:
 *   1. write through a **symlink** (or any non-regular file) — the write would
 *      land on the link's target instead of creating a sibling;
 *   2. clobber an existing regular file that does **not** carry the generated
 *      marker, i.e. one PythScribe did not produce (when `markerAware`).
 *
 * Residual TOCTOU between the `lstat` and the write matches the Rust writer and
 * the repository threat model, which places local concurrent filesystem
 * attackers out of scope.
 *
 * @param {string} target   absolute path to write
 * @param {string} contents file contents (utf-8)
 * @param {{ markerAware?: boolean }} [opts]
 * @throws {Error} when the write is refused
 */
export function writeGeneratedSibling(target, contents, { markerAware = true } = {}) {
    let st = null;
    try {
        st = lstatSync(target);
    } catch (err) {
        // FAIL CLOSED. Only "there is genuinely nothing here" authorizes a
        // create. Any other metadata failure (EACCES, EPERM, ELOOP, EIO…)
        // means we could NOT prove the destination is safe, and proceeding
        // would truncate whatever is actually there.
        if (!err || err.code !== "ENOENT") {
            throw new Error(
                `refusing to write generated output: could not inspect the destination\n` +
                `    ${target}\n  ${err && err.code ? err.code : err}`,
            );
        }
        st = null;
    }

    if (st) {
        if (st.isSymbolicLink()) {
            throw new Error(
                `refusing to write generated output through a symlink:\n    ${target}\n` +
                `  this path is a symbolic link; writing would modify its target instead of ` +
                `creating a compiled sibling.\n  Remove the link or disable emitDts.`,
            );
        }
        if (!st.isFile()) {
            throw new Error(
                `refusing to write generated output over a non-regular file:\n    ${target}`,
            );
        }
        // A file with more than one name is a HARDLINK: truncating it rewrites
        // every other name too, and lstat cannot tell us where those are. The
        // marker gate alone is not enough here because the shared contents may
        // legitimately (or maliciously) carry the marker.
        if (typeof st.nlink === "number" && st.nlink > 1) {
            throw new Error(
                `refusing to write generated output to a hard-linked file:\n    ${target}\n` +
                `  it has ${st.nlink} names, so writing would rewrite the other ones too.\n` +
                `  Break the link or disable emitDts.`,
            );
        }
        // P5: the marker/ownership check AND the write happen on ONE handle
        // inside overwriteVerified — open (no truncate) → fstat → verify marker
        // → ftruncate → write — so a symlink/file swapped in after this lstat
        // can neither redirect the write nor be truncated before it is proven
        // ours.
        overwriteVerified(target, contents, markerAware);
        return;
    }

    // Nothing at the destination: create EXCLUSIVELY. `wx` fails with EEXIST
    // rather than following a link that appeared between the lstat and here,
    // and it refuses a DANGLING symlink (which lstat reports, but a racing
    // one would not) instead of creating its target.
    try {
        writeFileSync(target, contents, { flag: "wx" });
    } catch (err) {
        if (err && err.code === "EEXIST") {
            throw new Error(
                `refusing to write generated output: the destination appeared while we were ` +
                `checking it\n    ${target}\n  Re-run the build.`,
            );
        }
        throw err;
    }
}

