// #6 — private per-invocation output directory
// ---------------------------------------------------------------------------

let __tmpSeq = 0;

/**
 * Create a fresh, unique, private directory for one compile invocation. JS port
 * of `procutil.rs::make_private_temp_dir`: exclusive creation (`recursive:
 * false` fails with EEXIST rather than reusing a planted directory) and mode
 * 0700 so other local users cannot read or plant files inside it.
 *
 * The caller compiles into this directory (`pyths compile -o <dir>/mod.js`) so
 * NO transient file is ever created — or deleted — beside the user's source.
 *
 * @param {string} tag short label embedded in the directory name
 * @returns {string} absolute path to the created directory
 */
export function makePrivateTempDir(tag) {
    const base = tmpdir();
    for (let attempt = 0; attempt < 64; attempt += 1) {
        const name = `pyths-${tag}-${process.pid}-${__tmpSeq++}-${Date.now()}-${
            Math.random().toString(36).slice(2, 10)
        }-${attempt}`;
        const dir = join(base, name);
        try {
            mkdirSync(dir, { recursive: false, mode: 0o700 });
            return dir;
        } catch (err) {
            if (err && err.code === "EEXIST") continue;
            throw err;
        }
    }
    throw new Error("could not create a unique private temp directory after 64 attempts");
}

/** Best-effort recursive removal of a directory created by `makePrivateTempDir`. */
export function removePrivateTempDir(dir) {
    try {
        rmSync(dir, { recursive: true, force: true });
    } catch {
        /* best effort — a leftover temp dir is not worth failing a build over */
    }
}

