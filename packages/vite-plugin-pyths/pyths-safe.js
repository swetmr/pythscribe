// ===========================================================================
//  pyths-safe.js — the ONE safe API the PythScribe build plugins must use for
//  (a) selecting the compiler executable and (b) touching the filesystem.
//
//  SHARED SOURCE — this file is duplicated BYTE-FOR-BYTE into every plugin
//  package (`packages/vite-plugin-pyths/`, `packages/next-plugin-pyths/`)
//  because each package is published to npm standalone and cannot import from
//  a sibling. `test-safe-parity.mjs` in each package fails if the copies drift.
//  Edit one, copy to the other, run both test files.
//
//  ---------------------------------------------------------------------------
//  Why this file exists (security scan 2026-08-12, findings #1 / #2 / #6)
//
//  The CLI (`crates/pyths_cli`) was hardened during the OWASP campaign: it
//  resolves programs through `procutil.rs::resolve_program` (PATH only, never
//  the cwd) and writes generated files through
//  `compile.rs::write_generated_sibling` (no-follow + ownership-aware). The
//  build plugins re-implemented both with plain `execFileSync("pyths", …)` and
//  `writeFileSync`/`unlinkSync`, so the same defect classes survived on the
//  plugin side. This module ports those two controls to JavaScript.
//
//    #1 CWE-426 untrusted search path — a bare program name is resolved by the
//       OS/libuv at spawn time. A `.` element in PATH (very common on Windows)
//       makes that search include the CURRENT DIRECTORY, so a hostile repo
//       shipping `./pyths.exe` gets code execution the moment a developer runs
//       `vite build`. Reproduced on Node 22 / win32; see
//       `test-resolve-bin.mjs::"a . entry in PATH must not select a
//       cwd-planted executable"`.
//
//    #2 CWE-59 symlink follow — `writeFileSync(declPath, …)` follows a
//       final-component symlink, so a checked-in `Foo.d.ps.ts -> ~/.bashrc`
//       has the plugin write generated content into the link target.
//
//    #6 CWE-73 unowned deletion — the old `finally` block unlinked
//       `<stem>.js` / `.js.map` / `.d.ts` beside the SOURCE whenever they
//       existed, deleting hand-written project files the CLI itself refuses to
//       overwrite. Fixed by compiling into a private per-invocation directory
//       (`makePrivateTempDir`) so nothing adjacent to the source is ever
//       created or removed.
// ===========================================================================

